"use client";

import { useCallback, useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import {
  getSupabaseBrowserClient,
  isSupabaseConfigured,
  SUPABASE_CONFIG_MESSAGE,
} from "@/lib/supabase/client";
import { Button } from "@/components/ui/button";
import { AuthNotice } from "./AuthNotice";

type Mode = "loading" | "enroll" | "challenge";

/**
 * One screen for both TOTP jobs (SPEC: enrollment at sign-up, challenge at
 * sign-in). The mode is derived from the account's factors, not from the URL,
 * so refresh/deep-links always land in the right state.
 */
export function TotpForm() {
  const router = useRouter();
  const [mode, setMode] = useState<Mode>("loading");
  const [factorId, setFactorId] = useState<string | null>(null);
  const [challengeId, setChallengeId] = useState<string | null>(null);
  const [qrSvg, setQrSvg] = useState<string | null>(null);
  const [secret, setSecret] = useState<string | null>(null);
  const [code, setCode] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const startChallenge = useCallback(async (fid: string) => {
    const supabase = getSupabaseBrowserClient();
    const { data, error: err } = await supabase.auth.mfa.challenge({
      factorId: fid,
    });
    if (err) throw new Error(err.message);
    setChallengeId(data.id);
  }, []);

  const startEnroll = useCallback(async () => {
    const supabase = getSupabaseBrowserClient();
    // Remove abandoned (unverified) factors from previous attempts.
    const { data: factors } = await supabase.auth.mfa.listFactors();
    for (const f of factors?.totp ?? []) {
      if (f.status !== "verified") {
        await supabase.auth.mfa.unenroll({ factorId: f.id });
      }
    }
    const { data, error: err } = await supabase.auth.mfa.enroll({
      factorType: "totp",
      friendlyName: "Authenticator app",
    });
    if (err) throw new Error(err.message);
    setFactorId(data.id);
    setQrSvg(data.totp.qr_code);
    setSecret(data.totp.secret);
  }, []);

  useEffect(() => {
    if (!isSupabaseConfigured()) {
      setError(SUPABASE_CONFIG_MESSAGE);
      return;
    }
    (async () => {
      try {
        const supabase = getSupabaseBrowserClient();
        const {
          data: { user },
        } = await supabase.auth.getUser();
        if (!user) {
          router.replace("/login");
          return;
        }
        const { data: factors } = await supabase.auth.mfa.listFactors();
        const verified = (factors?.totp ?? []).find(
          (f) => f.status === "verified",
        );
        if (verified) {
          setFactorId(verified.id);
          await startChallenge(verified.id);
          setMode("challenge");
        } else {
          await startEnroll();
          setMode("enroll");
        }
      } catch (e) {
        setError(e instanceof Error ? e.message : "Could not start 2FA setup.");
      }
    })();
  }, [router, startChallenge, startEnroll]);

  async function onVerify(e: React.FormEvent) {
    e.preventDefault();
    if (!factorId) return;
    setBusy(true);
    setError(null);
    try {
      const supabase = getSupabaseBrowserClient();
      let cid = challengeId;
      if (!cid) {
        const { data, error: err } = await supabase.auth.mfa.challenge({
          factorId,
        });
        if (err) throw new Error(err.message);
        cid = data.id;
        setChallengeId(cid);
      }
      const { error: verifyError } = await supabase.auth.mfa.verify({
        factorId,
        challengeId: cid,
        code: code.trim(),
      });
      if (verifyError) {
        // Challenges are single-use — mint a fresh one for the retry.
        setError("That code didn't work. Check your app and try again.");
        setCode("");
        await startChallenge(factorId);
        return;
      }
      router.push("/app");
      router.refresh();
    } catch (e2) {
      setError(e2 instanceof Error ? e2.message : "Verification failed.");
    } finally {
      setBusy(false);
    }
  }

  if (error && mode === "loading") {
    return <AuthNotice kind="error">{error}</AuthNotice>;
  }

  if (mode === "loading") {
    return <p className="text-sm text-stone-500">Preparing 2FA…</p>;
  }

  return (
    <form onSubmit={onVerify} className="auth-form space-y-4">
      {mode === "enroll" ? (
        <div className="space-y-3">
          <p className="text-sm text-stone-600">
            Scan this code with an authenticator app (Google Authenticator,
            1Password, Authy…), then enter the 6-digit code.
          </p>
          {qrSvg ? (
            <div
              className="mx-auto w-44 rounded-lg border border-stone-200 bg-white p-2 [&_svg]:h-auto [&_svg]:w-full"
              // QR SVG is generated by Supabase for this account's factor.
              dangerouslySetInnerHTML={{ __html: qrSvg }}
            />
          ) : null}
          {secret ? (
            <p className="break-all rounded-md bg-stone-100 px-3 py-2 text-center font-mono text-xs text-stone-700">
              Manual entry: {secret}
            </p>
          ) : null}
        </div>
      ) : (
        <p className="text-sm text-stone-600">
          Enter the 6-digit code from your authenticator app to finish signing
          in.
        </p>
      )}

      {error ? <AuthNotice kind="error">{error}</AuthNotice> : null}

      <input
        className="auth-field auth-code w-full rounded-md border border-stone-300 px-3 py-2 text-center text-lg tracking-[0.5em]"
        placeholder="000000"
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="[0-9]{6}"
        maxLength={6}
        required
        value={code}
        onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
      />
      <Button type="submit" className="auth-submit w-full" disabled={busy}>
        {busy ? "Verifying…" : mode === "enroll" ? "Enable 2FA" : "Verify"}
      </Button>
      <p className="text-center text-xs text-stone-500">
        Wrong account?{" "}
        <button
          type="button"
          className="text-teal-800 underline"
          onClick={async () => {
            await getSupabaseBrowserClient().auth.signOut();
            router.push("/login");
            router.refresh();
          }}
        >
          Sign out
        </button>
      </p>
    </form>
  );
}
